export const dictionaries = { de, en }

/**
 * Keys are often built at runtime (`status.${kind}.${status}`), so `t` takes any string;
 * the test suite checks that every key used in the code exists in both languages.
 */
export type T = (key: string, vars?: Record<string, string | number>) => string

interface LangValue {
  lang: Lang
  setLang(l: Lang): void
  t: T
  /** pick the entry for the current language from a [de, en] pair */
  pick(pair: [string, string]): string
}

const Ctx = createContext<LangValue | null>(null)
const LANG_KEY = 'mybib:lang'

function initialLang(): Lang {
  try {
    const stored = localStorage.getItem(LANG_KEY)
    if (stored === 'de' || stored === 'en') return stored
  } catch {
    /* ignore */
  }
  return navigator.language?.toLowerCase().startsWith('en') ? 'en' : 'de'
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang)
  const setLang = (l: Lang) => {
    setLangState(l)
    document.documentElement.lang = l
    try {
      localStorage.setItem(LANG_KEY, l)
    } catch {
      /* ignore */
    }
  }
  const dict: Record<string, string> = lang === 'de' ? de : en
  const t: T = (key, vars) => {
    let s: string = dict[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
    return s
  }
  const pick = useCallback((pair: [string, string]) => pair[lang === 'de' ? 0 : 1], [lang])
  return <Ctx.Provider value={{ lang, setLang, t, pick }}>{children}</Ctx.Provider>
}

export function useLang(): LangValue {
  const v = useContext(Ctx)
  if (!v) throw new Error('useLang outside LangProvider')
  return v
}
